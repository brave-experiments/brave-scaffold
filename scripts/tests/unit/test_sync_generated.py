class GeneratedCopyTests(SyncFixture):
    def test_renderer_denies_writes_and_child_processes(self):
        probe = Path(sync_model.__file__).with_name('generated_probe.py')
        target = self.core / 'must-not-exist'
        code = """
import os, runpy, subprocess, sys
probe = runpy.run_path(sys.argv[1])
sys.addaudithook(probe['deny_mutation'])
for action in (lambda: open(sys.argv[2], 'w'),
               lambda: os.mkdir(sys.argv[2]),
               lambda: subprocess.run([sys.executable, '-c', 'pass'])):
    try:
        action()
    except PermissionError:
        print('denied')
    else:
        raise AssertionError('mutation permitted')
"""
        result = subprocess.run([sys.executable, '-I', '-B', '-c', code, str(probe), str(target)],
                                capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(result.stdout.splitlines(), ['denied'] * 3)
        self.assertFalse(target.exists())

    def test_exact_copy_is_known_but_an_edit_or_symlink_is_not(self):
        source, target = self.core / 'strings.grd', self.src / 'strings.grd'
        source.write_text('generated strings')
        target.write_bytes(source.read_bytes())
        copies = [(source, target)]
        self.assertEqual(sync_model.matching_copies(self.identity, copies), {target})
        target.write_text('generated strings plus local work')
        self.assertEqual(sync_model.matching_copies(self.identity, copies), set())
        target.unlink()
        target.symlink_to(source)
        self.assertEqual(sync_model.matching_copies(self.identity, copies), set())

    def test_devtools_requires_reviewed_producer_and_actual_hardlink(self):
        producer = self.core / 'wrapper.py'
        producer.write_text('reviewed wrapper')
        contracts = {'devtools_hardlink_source': {'path': 'wrapper.py',
            'sha256': hashlib.sha256(producer.read_bytes()).hexdigest()}}
        relative = 'third_party/devtools-frontend/src/front_end/example'
        source = self.core / 'chromium_src' / (relative + '.ts')
        target = self.src / (relative + '.patch.ts')
        source.parent.mkdir(parents=True)
        target.parent.mkdir(parents=True)
        source.write_text('override')
        target.write_bytes(source.read_bytes())
        self.assertEqual(sync_model.devtools_hardlinks(self.identity, contracts), set())
        target.unlink()
        os.link(source, target)
        self.assertEqual(sync_model.devtools_hardlinks(self.identity, contracts), {target})
        producer.write_text('different writer')
        self.assertEqual(sync_model.devtools_hardlinks(self.identity, contracts), set())

    def test_old_copy_needs_sync_ref_and_same_reviewed_copier(self):
        contracts = {'generated_sources': {}}
        for name in ('build/commands/lib/branding.js', 'build/commands/lib/l10nUtil.js'):
            path = self.core / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text('reviewed copier')
            contracts['generated_sources'][name] = hashlib.sha256(path.read_bytes()).hexdigest()
        source, target = self.core / 'strings.grd', self.src / 'strings.grd'
        source.write_text('old generated bytes')
        target.write_bytes(source.read_bytes())
        package = self.core / 'package.json'
        package.write_text(json.dumps({'config': {'projects': {'chrome': {'tag': 'old'}}}}))
        self.git(self.core, 'add', '.')
        self.git(self.core, 'commit', '-qm', 'old sources')
        source.write_text('new generated bytes')
        package.write_text(json.dumps({'config': {'projects': {'chrome': {'tag': 'new'}}}}))
        self.git(self.core, 'add', '.')
        self.git(self.core, 'commit', '-qm', 'new sources')
        self.git(self.src, 'tag', 'old')
        receipt = self.identity.workspace / '.brave_latest_successful_sync.json'
        receipt.write_text(json.dumps({'chromiumRef': 'refs/tags/old'}))
        copies = [(source, target)]
        self.assertEqual(sync_model.previous_branding_copies(self.identity, copies, set(), contracts), {target})
        target.write_text('old generated bytes plus my edit')
        self.assertEqual(sync_model.previous_branding_copies(self.identity, copies, set(), contracts), set())
        target.write_text('old generated bytes')
        contracts['generated_sources']['build/commands/lib/branding.js'] = 'unreviewed'
        self.assertEqual(sync_model.previous_branding_copies(self.identity, copies, set(), contracts), set())
        receipt.unlink()
        self.assertEqual(sync_model.previous_branding_copies(self.identity, copies, set(), contracts), set())

    def test_known_copy_never_excuses_staged_content(self):
        target = self.src / 'work.cc'
        source = self.core / 'strings.grd'
        source.write_text('generated')
        target.write_text('staged experiment')
        self.git(self.src, 'add', 'work.cc')
        target.write_text('generated')
        expected = sync_model.matching_copies(self.identity, [(source,target)])
        conflicts = sync_scope.local_work(self.identity, self.scope, expected, {})
        self.assertTrue(any('staged' in c['reason'] for c in conflicts))
        self.assertEqual(self.git(self.src, 'show', ':work.cc').stdout, 'staged experiment')


class IncomingHookTests(SyncFixture):
    def contract(self, hook, source='known source'):
        key = hashlib.sha256(ast.dump(ast.parse(hook, mode='eval').body).encode()).hexdigest()
        return {'hooks': {key: {'sources': {'hook.py': hashlib.sha256(source.encode()).hexdigest()},
                                'writes': ['generated']}}}

    def commit(self, name):
        self.git(self.src, 'add', 'DEPS', 'hook.py')
        self.git(self.src, 'commit', '-qm', name)
        return self.git(self.src, 'rev-parse', 'HEAD').stdout.strip()

    def test_reads_requested_revision_without_switching_worktree(self):
        hook = "[{'name':'generate','action':['python3','hook.py']}]"
        (self.src/'DEPS').write_text('hooks = []\n')
        (self.src/'hook.py').write_text('known source')
        before = self.commit('old')
        (self.src/'DEPS').write_text('hooks = '+hook+'\n')
        target = self.commit('new')
        self.git(self.src,'checkout','--detach',before)
        writes, unknown = incoming_hooks.inspect(self.identity,target,self.contract(hook))
        self.assertEqual(unknown,[])
        self.assertIn(self.src/'generated',writes)
        self.assertEqual((self.src/'DEPS').read_text(),'hooks = []\n')
        self.assertEqual(self.git(self.src,'rev-parse','HEAD').stdout.strip(),before)

    def test_changed_incoming_source_is_not_approved_by_old_hook_list(self):
        hook = "[{'name':'generate','action':['python3','hook.py']}]"
        (self.src/'DEPS').write_text('hooks = '+hook+'\n')
        (self.src/'hook.py').write_text('known source')
        before=self.commit('old')
        (self.src/'hook.py').write_text('new writes outside reviewed scope')
        target=self.commit('new')
        self.git(self.src,'checkout','--detach',before)
        _, unknown=incoming_hooks.inspect(self.identity,target,self.contract(hook))
        self.assertTrue(any('unreviewed incoming hook source' in x for x in unknown))

    def test_missing_target_never_fetches_or_changes_refs(self):
        with patch.object(incoming_hooks.Trees,'git',side_effect=incoming_hooks.Unavailable('missing')) as git:
            _,unknown=incoming_hooks.inspect(self.identity,'missing',{'hooks':{}})
        self.assertTrue(unknown)
        self.assertFalse(any('fetch' in args.args[1] for args in git.call_args_list))


class DependencyConditionTests(SyncFixture):
    def test_inactive_internal_directory_does_not_require_its_revision(self):
        (self.src/'DEPS').write_text("vars = {'checkout_src_internal': False}\n"
            "deps = {'src/internal': {'url': 'https://example.invalid/repo@missing', "
            "'condition': 'checkout_ios and checkout_src_internal'}}\n"
            "recursedeps = ['src/internal']\nhooks = []\n")
        (self.src/'internal').mkdir()
        self.git(self.src, 'add', 'DEPS')
        self.git(self.src, 'commit', '-qm', 'deps')
        _, problems = incoming_hooks.inspect(self.identity, 'HEAD', {'hooks': {}},
                                             variables={'checkout_ios': True})
        self.assertEqual(problems, [])
        _, problems = incoming_hooks.inspect(self.identity, 'HEAD', {'hooks': {}},
                         variables={'checkout_ios': True, 'checkout_src_internal': True})
        self.assertTrue(problems)

    def test_var_pin_is_read_without_executing_deps(self):
        deps = incoming_hooks.Deps("vars = {'repo': 'https://example.invalid', 'revision': 'abc'}\n"
                                   "deps = {'src/nested': Var('repo') + '@' + Var('revision')}\n"
                                   "raise RuntimeError('must not execute')\n")
        self.assertEqual(deps.pin('src/nested'), 'abc')

    def test_unavailable_active_recursive_dependency_stays_unknown(self):
        (self.src/'DEPS').write_text("deps = {'src/missing': 'https://example.invalid/repo@abc'}\n"
                                   "recursedeps = ['src/missing']\n")
        self.git(self.src, 'add', 'DEPS')
        self.git(self.src, 'commit', '-qm', 'deps')
        _, problems = incoming_hooks.inspect(self.identity, 'HEAD', {'hooks': {}})
        self.assertTrue(any('not available locally' in p for p in problems))

    def test_parent_variables_control_nested_dependency_conditions(self):
        child = self.src / 'nested'
        child.mkdir()
        self.git(child, 'init', '-q')
        (child / 'DEPS').write_text("vars = {'build_with_chromium': False}\n"
            "use_relative_paths = True\n"
            "deps = {'missing': {'url': 'https://example.invalid/repo@missing', "
            "'condition': 'not build_with_chromium'}}\nrecursedeps = ['missing']\n")
        self.git(child, 'add', 'DEPS')
        self.git(child, 'commit', '-qm', 'nested deps')
        revision = self.git(child, 'rev-parse', 'HEAD').stdout.strip()
        (self.src / 'DEPS').write_text("vars = {'build_with_chromium': True}\n"
            f"deps = {{'src/nested': 'https://example.invalid/repo@{revision}'}}\n"
            "recursedeps = ['src/nested']\n")
        self.git(self.src, 'add', 'DEPS')
        self.git(self.src, 'commit', '-qm', 'parent deps')
        _, problems = incoming_hooks.inspect(self.identity, 'HEAD', {'hooks': {}})
        self.assertEqual(problems, [])
        _, problems = incoming_hooks.inspect(self.identity, 'HEAD', {'hooks': {}},
                                             variables={'build_with_chromium': False})
        self.assertTrue(any('not available locally' in p for p in problems))


class UntrackedPreservationTests(SyncFixture):
    def test_disabled_depot_updates_require_reviewed_launcher_and_no_reinstall(self):
        depot = self.core / 'depot'
        depot.mkdir()
        launcher = depot / 'gclient'
        launcher.write_text('reviewed launcher')
        contracts = {'depot_update_sources': {'gclient': hashlib.sha256(launcher.read_bytes()).hexdigest()}}
        frozen = {'DEPOT_TOOLS_UPDATE': '0'}
        self.assertTrue(sync_model.depot_will_change(depot, None, None, {}, contracts))
        self.assertFalse(sync_model.depot_will_change(depot, None, None, frozen, contracts))
        self.assertTrue(sync_model.depot_will_change(depot, None, 'new-ref', frozen, contracts))
        launcher.write_text('different launcher')
        self.assertTrue(sync_model.depot_will_change(depot, None, None, frozen, contracts))
        launcher.write_text('reviewed launcher')
        Path(str(depot) + '_install.guard').touch()
        self.assertTrue(sync_model.depot_will_change(depot, None, None, frozen, contracts))

    def test_known_detached_trees_preserve_unrelated_untracked_work(self):
        old = self.git(self.src, 'rev-parse', 'HEAD').stdout.strip()
        (self.src / 'incoming.cc').write_text('incoming source')
        self.git(self.src, 'add', 'incoming.cc')
        self.git(self.src, 'commit', '-qm', 'incoming')
        target = self.git(self.src, 'rev-parse', 'HEAD').stdout.strip()
        self.git(self.src, 'checkout', '--detach', old)
        note = self.src / 'notes.txt'
        note.write_text('keep this')
        incoming = {self.src: (self.src, target)}
        def guard(**kwargs):
            return sync_scope.local_work(self.identity, self.scope, set(), {},
                                         incoming_trees=incoming, **kwargs)
        self.assertEqual(guard(), [])
        self.assertTrue(guard(writes={note: 'hook'}))
        self.assertTrue(guard(unknown_writes=['unknown hook']))
        (self.src / 'incoming.cc').mkdir()
        (self.src / 'incoming.cc' / 'scratch.txt').write_text('keep too')
        conflicts = guard()
        self.assertEqual([c['path'] for c in conflicts], ['incoming.cc/scratch.txt'])
        self.assertEqual(note.read_text(), 'keep this')
        self.git(self.src, 'checkout', '-b', 'local')
        self.assertIsNone(sync_scope.reset_paths(self.src, (self.src, target)))

    def test_collision_checks_include_case_and_both_ancestor_directions(self):
        for path, tracked in [('Node_Modules/pkg/data', {'node_modules'}),
                              ('node_modules', {'node_modules/pkg/data'}),
                              ('file', {'FILE'})]:
            with self.subTest(path=path):
                self.assertTrue(sync_scope.path_collision(path, tracked))
        self.assertFalse(sync_scope.path_collision('notes', {'notes-other'}))

    def test_only_fully_disabled_known_hook_groups_skip_writes(self):
        deps = incoming_hooks.Deps("vars = {'enabled': False}\n")
        deps.overrides = deps.variables()
        disabled = ast.parse("[{'condition': 'enabled', 'action': ['writer']}]", mode='eval').body
        self.assertTrue(deps.hooks_disabled(disabled))
        deps.overrides['enabled'] = True
        self.assertFalse(deps.hooks_disabled(disabled))
        unknown = ast.parse("[{'condition': 'missing', 'action': ['writer']}]", mode='eval').body
        self.assertFalse(deps.hooks_disabled(unknown))
        unconditional = ast.parse("[{'action': ['writer']}]", mode='eval').body
        self.assertFalse(deps.hooks_disabled(unconditional))
